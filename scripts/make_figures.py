#!/usr/bin/env python
"""
Charts and tables for Part 2 of the panorama stitching analysis.

Builds visual outputs and markdown summaries from the CSV files generated by 
`run_synthetic.py` and `run_scenes.py`.

Usage:
    $ python scripts/make_figures.py

Outputs generated:
    data/panorama/result/figures/sweep_success.png   correct homographies vs difficulty (synthetic)
    data/panorama/result/figures/sweep_error.png     geometric error of the correct ones
    data/panorama/result/figures/sweep_inliers.png   how many RANSAC inliers survive
    data/panorama/result/figures/scenes_metrics.png  real scenes: inlier ratio, RMSE, overlap agreement
    data/panorama/result/figures/runtime.png         run time of the pipeline stages
    data/panorama/result/synthetic/summary.csv       the numbers behind the sweep charts ("table view")
    data/panorama/result/synthetic/summary.md        markdown tables + the limit of every extractor
    data/panorama/result/scenes_summary.md           markdown tables of the real scenes
"""
from __future__ import annotations

import csv
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from panorama import viz
from panorama.config import PANO_RESULT_DIR
from panorama.features import METHODS
from panorama.synthetic import SWEEPS, nominal_overlap

TOL = 3.0 # a homography counts as correct if its error against the ground truth is below this (px)
LIMIT = 0.9 # "limit" of an extractor = hardest level at which at least 90 % of the trials succeed
LABEL = {m: viz.SERIES[m]["label"] for m in METHODS}


def synthetic_outputs(res_dir: Path) -> None:
    """
    Generates charts and tables summarizing the synthetic robustness experiments.

    Reads `trials.csv`, aggregates the data across difficulty sweeps, creates line 
    charts for success rate, geometric error, and inlier counts, and writes detailed 
    CSV and Markdown summaries.

    Args:
        res_dir (Path): The base result directory where `synthetic/trials.csv` is located.
    """
    rows = viz.read_csv(res_dir / "synthetic" / "trials.csv")
    agg = viz.aggregate_sweeps(rows, TOL)
    n_trials = int(max(d["n"] for lv in agg.values() for d in lv))

    ov = SWEEPS["overlap"][1]
    tick_labels = {"overlap": [f"{lv:g}°\n{100 * nominal_overlap('overlap', lv):.0f} %" for lv in ov]}
    xlabels = {"overlap": "Angle between the views / overlap of the views"}
    for metric, name, title in (
            ("success", "sweep_success", f"Share of trials with a correct homography (error < {TOL:g} px), {n_trials} trials per point"),
            ("error", "sweep_error", "Geometric error against the ground truth (median over the correct homographies)"),
            ("inliers", "sweep_inliers", "RANSAC inliers (median over the trials): how much evidence the extractor delivers")
    ):
        viz.save_figure(
            viz.sweep_figure(agg, SWEEPS, metric, TOL, title=title, tick_labels=tick_labels, xlabels=xlabels),
            res_dir / "figures" / f"{name}.png", dpi=140
        )

    # table view
    fields = [
        "sweep", "method", "level", "n", "accepted", "correct", "wrong_accept", "success", "ci_lo", "ci_hi",
        "median_err_px", "median_inliers", "median_keypoints"
    ]
    with open(res_dir / "synthetic" / "summary.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(fields)
        for (sweep, m), lv in agg.items():
            for d in lv:
                w.writerow(
                    [sweep, m, d["level"], d["n"], d["accepted"], d["correct"], d["wrong_accept"],
                    round(d["success"], 4), round(d["ci_lo"], 4), round(d["ci_hi"], 4),
                    "" if np.isnan(d["median_err"]) else round(d["median_err"], 3), d["median_inl"], d["median_kp"]]
                )

    md = [
        f"Correct homographies = pair accepted and geometric error against the ground truth below {TOL:g} px; "
        f"{n_trials} trials per level. Cells: `correct/trials` and, in brackets, the median error in px of the correct ones.\n"
    ]
    limits = {m: {} for m in METHODS}
    for sweep, (_, levels) in SWEEPS.items():
        labels = tick_labels.get(sweep, [f"{lv:g}" for lv in levels])
        head = [{"overlap": "angle / overlap"}.get(sweep, sweep)] + [LABEL[m] for m in METHODS]
        body = []
        for li, lab in enumerate(labels):
            row = [lab.replace("\n", " / ")]
            for m in METHODS:
                d = agg[(sweep, m)][li]
                err = "-" if np.isnan(d["median_err"]) else f"{d['median_err']:.2f}"
                row.append(f"{d['correct']}/{d['n']} ({err})")
            body.append(row)
        md += [f"**{sweep}** - {SWEEPS[sweep][0]}\n", viz.markdown_table(head, body, "lccc"), ""]
        for m in METHODS:                                      # hardest level that is still solved >= 90 % of the time
            ok = [d for d in agg[(sweep, m)] if d["success"] >= LIMIT]
            reach = 0
            for d in agg[(sweep, m)]:
                if d["success"] >= LIMIT:
                    reach += 1
                else:
                    break
            limits[m][sweep] = (labels[reach - 1].replace("\n", " / ") if reach else "none", reach == len(labels))

    head = ["factor"] + [LABEL[m] for m in METHODS]
    body = []
    for sweep in SWEEPS:
        row = [sweep]
        for m in METHODS:
            lab, full = limits[m][sweep]
            row.append(f"{lab}" + (" (all levels)" if full else ""))
        body.append(row)
    md += [f"**Limit of every extractor** - hardest level (levels are ordered easy to hard) up to which at least "
           f"{100 * LIMIT:.0f} % of the trials are solved:\n", viz.markdown_table(head, body, "lccc"), ""]
    (res_dir / "synthetic" / "summary.md").write_text("\n".join(md))


def scene_outputs(res_dir: Path) -> None:
    """
    Generates charts and tables summarizing performance on the real-world scenes.

    Reads `scenes.csv`, creates grouped bar charts comparing RANSAC inlier ratios, 
    RMSE, overlap agreements, and runtime per stage. Writes a detailed Markdown summary.

    Args:
        res_dir (Path): The base result directory where `scenes.csv` is located.
    """
    rows = viz.read_csv(res_dir / "scenes.csv")
    scenes = list(dict.fromkeys(r["scene"] for r in rows))
    get = lambda m, key: [next(r[key] for r in rows if r["scene"] == s and r["method"] == m) for s in scenes]

    # metrics of the real scenes
    viz.apply_style()
    fig, axes = plt.subplots(2, 2, figsize=(11.5, 7.6))
    panels = [
        ("inlier_ratio", "RANSAC inliers / putative matches", "Inlier ratio  (higher is better)", False),
        ("rmse_tree", "RMS reprojection error (px)", "Alignment error of the inliers  (lower is better)", False),
        ("ncc_hp_tree", "high-pass NCC in the overlap", "Agreement of the overlaps, structure  (higher is better)", False),
        ("mae_tree", "mean |difference| (grey levels)", "Agreement of the overlaps, intensity  (lower is better)", False)
    ]
    viz.grouped_bars(
        axes.ravel(), [s for s in scenes], [{m: get(m, k) for m in METHODS} for k, *_ in panels],
        [p[1] for p in panels], [p[2] for p in panels]
    )
    for ax, (k, *_rest) in zip(axes.ravel(), panels):
        if k in ("inlier_ratio", "ncc_hp_tree"):
            ax.set_ylim(0, 1.0)
    fig.legend(
        handles=viz.method_handles(with_line=False), loc="upper center", ncol=3, bbox_to_anchor=(0.5, 1.02),
        columnspacing=2.5
    )
    fig.tight_layout(rect=(0, 0, 1, 0.97), h_pad=2.0, w_pad=2.0)
    viz.save_figure(fig, res_dir / "figures" / "scenes_metrics.png", dpi=140)

    # run time per stage
    n_img = np.array([next(r["n_images"] for r in rows if r["scene"] == s) for s in scenes])
    n_pair = n_img * (n_img - 1) / 2
    stages = [
        ("features", "t_features", n_img, "Feature extraction\n(per image)"),
        ("matching", "t_matching", n_pair, "Matching\n(per image pair)"),
        ("ransac", "t_ransac", n_pair, "RANSAC\n(per image pair)")
    ]
    fig, ax = plt.subplots(figsize=(7.5, 4.0))
    x = np.arange(len(stages))
    w = 17.0 / (ax.get_position().width * fig.get_figwidth() * fig.dpi / len(stages))
    per_ms = {m: [1000.0 * float(np.sum(get(m, key)) / np.sum(div)) for _, key, div, _ in stages] for m in METHODS}
    for mi, m in enumerate(METHODS):
        ax.bar(x + (mi - 1) * w * 1.1, per_ms[m], width=w, color=viz.SERIES[m]["color"], zorder=3)
    ax.set_xticks(x)
    ax.set_xticklabels([s[3] for s in stages])
    ax.set_ylabel("milliseconds")
    ax.grid(axis="x", visible=False)
    ax.legend(handles=viz.method_handles(with_line=False), loc="upper right")
    ax.set_title("Run time of the extractor-dependent stages (mean over all scenes)")
    fig.tight_layout()
    viz.save_figure(fig, res_dir / "figures" / "runtime.png", dpi=140)

    # markdown tables
    md = [
        "Real scenes, multi-band blending, default parameters.  inliers = RANSAC inliers on the pairs of the spanning tree, "
        "ratio = inliers / putative matches, RMSE = RMS reprojection error of the inliers (px), NCC / MAE = agreement of the "
        "warped images inside their overlaps (high-pass NCC: 1 is perfect; MAE in grey levels).\n"
    ]
    head = ["scene", "extractor", "keypoints / image", "inliers", "ratio", "RMSE px", "NCC high-pass", "MAE", "time s"]
    body = []
    for s in scenes:
        for m in METHODS:
            r = next(x for x in rows if x["scene"] == s and x["method"] == m)
            body.append(
                [s, LABEL[m], f"{r['kp_mean']:.0f}", f"{r['inliers_tree']:.0f}", f"{r['inlier_ratio']:.2f}",
                f"{r['rmse_tree']:.2f}", f"{r['ncc_hp_tree']:.3f}", f"{r['mae_tree']:.1f}", f"{r['t_total']:.1f}"]
            )
    md += [viz.markdown_table(head, body, "llrrrrrrr"), ""]
    md += ["Mean over the scenes:\n"]
    body = []
    for m in METHODS:
        sel = [r for r in rows if r["method"] == m]
        mean = lambda k: float(np.nanmean([r[k] for r in sel]))
        body.append([LABEL[m], f"{mean('kp_mean'):.0f}", f"{mean('inlier_ratio'):.2f}", f"{mean('rmse_tree'):.2f}",
                     f"{mean('ncc_hp_tree'):.3f}", f"{mean('mae_tree'):.1f}", f"{mean('t_total'):.1f}"])
    md += [viz.markdown_table(["extractor", "keypoints / image", "ratio", "RMSE px", "NCC high-pass", "MAE", "time s"], body, "lrrrrrr"), ""]
    md += [
        f"Time per stage (ms, mean over all scenes): "
        + "; ".join(f"{LABEL[m]}: features/image {per_ms[m][0]:.0f}, matching/pair {per_ms[m][1]:.0f}, RANSAC/pair {per_ms[m][2]:.0f}"
        for m in METHODS), ""
    ]
    (res_dir / "scenes_summary.md").write_text("\n".join(md))


def main() -> None:
    """Entry point: Checks for required CSV files and orchestrates figure generation."""
    res_dir = PANO_RESULT_DIR
    if (res_dir / "synthetic" / "trials.csv").exists():
        synthetic_outputs(res_dir)
        print("synthetic figures and tables written")
    else:
        print("no synthetic/trials.csv - run scripts/run_synthetic.py first")
    if (res_dir / "scenes.csv").exists():
        scene_outputs(res_dir)
        print("scene figures and tables written")
    else:
        print("no scenes.csv - run scripts/run_scenes.py first")


if __name__ == "__main__":
    main()